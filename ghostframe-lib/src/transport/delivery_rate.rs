//! A generic algorithm for a transport protocol sender to estimate the current
//! delivery rate of its data on the fly.
//!
//! See
//! <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02>.
//!
//! # Provenance
//!
//! Ported from Tencent TQUIC, `src/congestion_control/delivery_rate.rs`,
//! commit `938e90adb460b5ff08b2bc6d11a3e1ba52c27a8d`
//! (<https://github.com/Tencent/tquic>), Apache-2.0. The licence header above
//! is TQUIC's and stays. See the repository's `NOTICE`.
//!
//! The estimator arithmetic is unchanged. What differs from upstream:
//!
//! - `crate::connection::space::{SentPacket, RateSamplePacketState,
//!   AckedPacket}` do not exist here. [`SentPacket`] and
//!   [`RateSamplePacketState`] are redefined below with only the fields the
//!   estimator reads or writes (`pkt_num`, `time_sent`, `time_acked`,
//!   `sent_size` and the rate-sample state); the connection, path and
//!   packet-number-space types are gone. `AckedPacket` was an unused import.
//! - `pkt_num` is a departure ordinal assigned by the caller, not a QUIC
//!   packet number; the estimator only compares and takes the maximum of them.
//! - `Default` is replaced by [`DeliveryRateEstimator::new`], which takes the
//!   clock reading instead of calling `Instant::now()`, so a harness on a
//!   virtual clock stays deterministic.
//! - [`DeliveryRateEstimator::sample_interval`] is new: it lets the caller
//!   tell a fresh sample from the previous one still standing.
//! - The struct shapes are those of `src/connection/space.rs` in the same
//!   commit (`SentPacket`, `RateSamplePacketState`), cut down to the fields
//!   used here.
//! - TQUIC's unit tests are not carried over; `delivery_sampler.rs` replays
//!   vectors generated by running the upstream file at the commit above (see
//!   `testdata/`).
//!
//! # Departures from the draft (inherited from TQUIC)
//!
//! Checked against draft-cheng-iccrg-delivery-rate-estimation-**02**, the
//! revision TQUIC cites. TQUIC departs from it in three ways; the port keeps
//! the arithmetic as it is, and the caller compensates where it can:
//!
//! - (a) `send_elapsed`, `ack_elapsed` and `rtt` are overwritten by every
//!   `update_rate_sample` call, so they come from the last-iterated packet,
//!   not from the newest one (the one with the greatest `delivered` at send,
//!   which is the draft's choice). `prior_delivered` and `prior_time` do
//!   follow the newest. `DeliverySampler` therefore calls
//!   `update_rate_sample` for a batch in `pkt_num` order, newest last, which
//!   restores the draft's behaviour without touching this file.
//! - (b) `rate_sample` is never reset between acknowledgements, so a field a
//!   later call does not rewrite keeps its previous value. The caller
//!   generates a sample only after at least one update.
//! - (c) The draft's guard that discards a sample whose interval is below the
//!   path's minimum RTT (`rs.interval < MinRTT`) is absent. A sample over a
//!   very short interval can therefore overstate the rate.
//!
//! The hooks are called from `delivery_sampler.rs`: `on_packet_sent` at a
//! datagram's departure from quinn's FIFO (F2), `update_rate_sample` and
//! `generate_rate_sample` from a `wire_seq` acknowledgement. Nothing here goes
//! through quinn's `Controller` trait.

use std::time::Duration;
use std::time::Instant;

/// The rate-sample state a packet carries from its send to its acknowledgement
/// (draft section 3.2, `P.delivered`, `P.delivered_time`, `P.first_sent_time`,
/// `P.is_app_limited`; `tx_in_flight` and `lost` are TQUIC's additions for BBR).
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct RateSamplePacketState {
    pub delivered: u64,
    pub delivered_time: Option<Instant>,
    pub first_sent_time: Option<Instant>,
    pub is_app_limited: bool,
    pub tx_in_flight: u64,
    pub lost: u64,
}

/// A transmission, as far as the estimator is concerned.
#[derive(Debug, Clone, Copy)]
pub struct SentPacket {
    pub pkt_num: u64,
    pub time_sent: Instant,
    pub time_acked: Option<Instant>,
    pub sent_size: usize,
    pub rate_sample_state: RateSamplePacketState,
}

/// Rate sample output.
///
/// See
/// <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.1.3>.
#[derive(Debug, Default)]
struct RateSample {
    /// rs.delivery_rate: The delivery rate sample (in most cases rs.delivered / rs.interval).
    delivery_rate: u64,

    /// rs.is_app_limited: The P.is_app_limited from the most recent packet delivered;
    /// indicates whether the rate sample is application-limited.
    is_app_limited: bool,

    /// rs.interval: The length of the sampling interval.
    interval: Duration,

    /// rs.delivered: The amount of data marked as delivered over the sampling interval.
    delivered: u64,

    /// rs.prior_delivered: The P.delivered count from the most recent packet delivered.
    prior_delivered: u64,

    /// rs.prior_time: The P.delivered_time from the most recent packet delivered.
    prior_time: Option<Instant>,

    /// rs.send_elapsed: Send time interval calculated from the most recent packet delivered.
    send_elapsed: Duration,

    /// rs.ack_elapsed: ACK time interval calculated from the most recent packet delivered.
    ack_elapsed: Duration,

    /// sample rtt.
    rtt: Duration,
}

/// Delivery rate estimator.
///
/// <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.1.1>.
#[derive(Debug)]
pub struct DeliveryRateEstimator {
    /// C.delivered: The total amount of data (measured in octets or in packets) delivered
    /// so far over the lifetime of the transport connection. This does not include pure ACK packets.
    delivered: u64,

    /// C.delivered_time: The wall clock time when C.delivered was last updated.
    delivered_time: Instant,

    /// C.first_sent_time: If packets are in flight, then this holds the send time of the packet that
    /// was most recently marked as delivered. Else, if the connection was recently idle, then this
    /// holds the send time of most recently sent packet.
    first_sent_time: Instant,

    /// C.app_limited: The index of the last transmitted packet marked as application-limited,
    /// or 0 if the connection is not currently application-limited.
    last_app_limited_pkt_num: u64,

    /// Record largest acked packet number to determine if app-limited state exits.
    largest_acked_pkt_num: u64,

    /// The last sent packet number.
    /// If application-limited occurs, it will be the end of last_app_limited_pkt_num.
    last_sent_pkt_num: u64,

    /// Rate sample.
    rate_sample: RateSample,
}

impl DeliveryRateEstimator {
    /// Upon each packet transmission.
    /// See <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.2>.
    pub fn on_packet_sent(
        &mut self,
        packet: &mut SentPacket,
        bytes_in_flight: u64,
        bytes_lost: u64,
    ) {
        // no packets in flight yet?
        if bytes_in_flight == 0 {
            self.first_sent_time = packet.time_sent;
            self.delivered_time = packet.time_sent;
        }

        packet.rate_sample_state.first_sent_time = Some(self.first_sent_time);
        packet.rate_sample_state.delivered_time = Some(self.delivered_time);
        packet.rate_sample_state.delivered = self.delivered;
        packet.rate_sample_state.is_app_limited = self.is_app_limited();
        packet.rate_sample_state.tx_in_flight = bytes_in_flight;
        packet.rate_sample_state.lost = bytes_lost;

        self.last_sent_pkt_num = packet.pkt_num;
    }

    /// Update rate sampler (rs) when a packet is SACKed or ACKed.
    /// See <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.3>.
    pub fn update_rate_sample(&mut self, packet: &mut SentPacket) {
        if packet.rate_sample_state.delivered_time.is_none() || packet.time_acked.is_none() {
            // Packet already SACKed or packet not acked
            return;
        }

        self.delivered = self.delivered.saturating_add(packet.sent_size as u64);
        // note: Update rate sample after P.time_acked got update. The default Instant::now() is
        // not accurate for estimating ack_elapsed.
        self.delivered_time = packet.time_acked.unwrap_or(Instant::now());

        // Update info using the newest packet:
        if self.rate_sample.prior_time.is_none()
            || packet.rate_sample_state.delivered > self.rate_sample.prior_delivered
        {
            self.rate_sample.prior_delivered = packet.rate_sample_state.delivered;
            self.rate_sample.prior_time = packet.rate_sample_state.delivered_time;
            self.rate_sample.is_app_limited = packet.rate_sample_state.is_app_limited;

            self.first_sent_time = packet.time_sent;
        }

        // Use each ACK to update delivery rate.
        self.rate_sample.send_elapsed = packet.time_sent.saturating_duration_since(
            packet
                .rate_sample_state
                .first_sent_time
                .unwrap_or(packet.time_sent),
        );
        self.rate_sample.ack_elapsed = self.delivered_time.saturating_duration_since(
            packet
                .rate_sample_state
                .delivered_time
                .unwrap_or(packet.time_sent),
        );
        self.rate_sample.rtt = self
            .delivered_time
            .saturating_duration_since(packet.time_sent);

        self.rate_sample.delivered = self
            .delivered
            .saturating_sub(self.rate_sample.prior_delivered);

        // Mark the packet as delivered once it's SACKed to
        // avoid being used again when it's cumulatively acked.
        packet.rate_sample_state.delivered_time = None;

        self.largest_acked_pkt_num = packet.pkt_num.max(self.largest_acked_pkt_num);
    }

    /// Upon receiving ACK, fill in delivery rate sample rs.
    /// See <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.3>.
    pub fn generate_rate_sample(&mut self) {
        // For each newly SACKed or ACKed packet P,
        //     `UpdateRateSample(P, rs)`
        // It's done before generate_rate_sample is called.

        // Clear app-limited field if bubble is ACKed and gone.
        if self.is_app_limited() && self.largest_acked_pkt_num > self.last_app_limited_pkt_num {
            self.set_app_limited(false);
        }

        // Nothing delivered on this ACK.
        if self.rate_sample.prior_time.is_none() {
            return;
        }

        // Use the longer of the send_elapsed and ack_elapsed.
        self.rate_sample.interval = self
            .rate_sample
            .send_elapsed
            .max(self.rate_sample.ack_elapsed);

        self.rate_sample.delivered = self
            .delivered
            .saturating_sub(self.rate_sample.prior_delivered);

        if self.rate_sample.interval.is_zero() {
            return;
        }

        self.rate_sample.delivery_rate = self.rate_sample.delivered * 1_000_000_u64
            / self.rate_sample.interval.as_micros() as u64;
    }

    /// Set app limited status and record the latest packet num as end of app limited mode.
    pub fn set_app_limited(&mut self, is_app_limited: bool) {
        self.last_app_limited_pkt_num = if is_app_limited {
            self.last_sent_pkt_num.max(1)
        } else {
            0
        }
    }

    /// Check if application limited.
    /// See <https://datatracker.ietf.org/doc/html/draft-cheng-iccrg-delivery-rate-estimation-02#section-3.4>.
    pub fn is_app_limited(&self) -> bool {
        self.last_app_limited_pkt_num != 0
    }

    /// C.delivered.
    pub fn delivered(&self) -> u64 {
        self.delivered
    }

    /// rs.delivered.
    pub fn sample_delivered(&self) -> u64 {
        self.rate_sample.delivered
    }

    /// rs.prior_delivered.
    pub fn sample_prior_delivered(&self) -> u64 {
        self.rate_sample.prior_delivered
    }

    /// Delivery rate.
    pub fn delivery_rate(&self) -> u64 {
        self.rate_sample.delivery_rate
    }

    /// Get rate sample rtt.
    pub fn sample_rtt(&self) -> Duration {
        self.rate_sample.rtt
    }

    /// rs.interval as the last `generate_rate_sample` left it (not in TQUIC).
    /// Read right after a `generate_rate_sample` that followed at least one
    /// `update_rate_sample`: zero then means the call produced no new rate (a
    /// zero interval returns early and `delivery_rate()` keeps its previous
    /// value). Before any update it is stale and means nothing.
    pub fn sample_interval(&self) -> Duration {
        self.rate_sample.interval
    }

    /// Check whether the current rate sample is application limited.
    pub fn is_sample_app_limited(&self) -> bool {
        self.rate_sample.is_app_limited
    }
}

impl DeliveryRateEstimator {
    /// A fresh estimator. `now` seeds the two clocks, which the first
    /// departure with nothing in flight overwrites anyway.
    pub fn new(now: Instant) -> Self {
        Self {
            delivered: 0,
            delivered_time: now,
            first_sent_time: now,
            last_app_limited_pkt_num: 0,
            largest_acked_pkt_num: 0,
            last_sent_pkt_num: 0,
            rate_sample: RateSample::default(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    /// Replays a trace through the port and compares every reading with what
    /// upstream's file produced on the same trace (see the vectors' header).
    /// Returns the number of readings compared and how many were app-limited,
    /// so a caller can prove both kinds of sample were reached.
    fn replay(vectors: &str, mark_app_limited: bool) -> (usize, usize, usize) {
        let base = Instant::now();
        let at = |us: u64| base + Duration::from_micros(us);
        let mut est = DeliveryRateEstimator::new(base);
        let mut pkts: HashMap<u64, SentPacket> = HashMap::new();
        let (mut compared, mut app_limited, mut mismatches) = (0, 0, 0);
        let mut lines = vectors.lines().filter(|l| !l.starts_with('#'));
        while let Some(line) = lines.next() {
            let f: Vec<&str> = line.split_whitespace().collect();
            match f[0] {
                "S" => {
                    let n: u64 = f[2].parse().unwrap();
                    let mut p = SentPacket {
                        pkt_num: n,
                        time_sent: at(f[1].parse().unwrap()),
                        time_acked: None,
                        sent_size: f[3].parse().unwrap(),
                        rate_sample_state: Default::default(),
                    };
                    est.on_packet_sent(&mut p, f[4].parse().unwrap(), f[5].parse().unwrap());
                    if !mark_app_limited {
                        // Mutation: the send path forgets the app-limited flag.
                        p.rate_sample_state.is_app_limited = false;
                    }
                    pkts.insert(n, p);
                }
                "L" => est.set_app_limited(f[1] == "1"),
                "A" => {
                    let t = at(f[1].parse().unwrap());
                    for n in f[2].split(',') {
                        let p = pkts.get_mut(&n.parse().unwrap()).unwrap();
                        p.time_acked = Some(t);
                        est.update_rate_sample(p);
                    }
                    est.generate_rate_sample();
                    let r = lines.next().expect("an R line follows every A");
                    let want: Vec<u64> = r
                        .split_whitespace()
                        .skip(1)
                        .map(|x| x.parse().unwrap())
                        .collect();
                    let got = [
                        est.delivery_rate(),
                        est.delivered(),
                        est.sample_delivered(),
                        est.sample_prior_delivered(),
                        est.is_sample_app_limited() as u64,
                        est.sample_rtt().as_micros() as u64,
                    ];
                    compared += 1;
                    app_limited += got[4] as usize;
                    if got.as_slice() != want.as_slice() {
                        mismatches += 1;
                    }
                }
                other => panic!("unknown trace line {other}"),
            }
        }
        (compared, app_limited, mismatches)
    }

    const VECTORS: &str = include_str!("testdata/delivery_rate_tquic_938e90a.txt");

    #[test]
    fn port_matches_upstream_on_the_recorded_trace() {
        let (compared, app_limited, mismatches) = replay(VECTORS, true);
        // Premises: the trace reached both kinds of sample, in bulk.
        assert!(compared > 1000, "only {compared} readings compared");
        assert!(app_limited > 50, "only {app_limited} app-limited readings");
        assert!(
            app_limited < compared - 500,
            "the trace is almost all app-limited"
        );
        assert_eq!(mismatches, 0, "port diverges from upstream");
    }

    /// Mutation guard: a send path that drops the app-limited marking must
    /// fail the comparison, or the vectors do not cover the app-limited case.
    #[test]
    fn dropping_the_app_limited_marking_is_caught() {
        let (_, _, mismatches) = replay(VECTORS, false);
        assert!(mismatches > 0, "vectors cannot see the marking");
    }
}
